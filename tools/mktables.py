#!/usr/bin/env python3
"""Generate precomputed tables (no floating point on the CoCo).

    mktables.py OUT.asm

The corridor projection follows the reference's R(z): k = 1/(1 + 0.85 z), with the reference's
800x440 view scaled to the CoCo's 640x136 view in logical x (CX 320, HW 320, CY 68, HH 68; the
line routine halves x for the 320-wide screen). A logical x unit is about 2.5x narrower than a row
is high, so 640x136 has nearly the reference's 800:440 shape on a
monitor, so no separate squash is needed.
"""
import sys

VIEW_W, VIEW_H = 640, 136
CX, HW = 320, 320
CY, HH = 68, 68
DEPTHS = 34                       # z = 0, 1/3, 2/3, ... 11 (index = 3z; range 7, +1 while gliding)


def k(i):
    z = i / 3                     # tables are indexed in thirds of a cell
    return 1 / (1 + 0.85 * z)


# Distance shading: the reference's bright(d, range), turned into a shade level 0 (bright) .. 4
# (faint); each kind of thing has a table of colour and dot pattern per level (in src/view.asm).
# Rows: 0 = no light, 1-8 = light range; columns: depth in thirds.
PATTERNS = [(0.9, 0), (0.65, 1), (0.4, 2), (0.2, 3), (0.0, 4)]

# Each kind of thing's colours and dots per level: wallshd, monshd, itemshd, ladshd in src/view.asm.


def bright(d, rng):
    if rng == 0:                                  # no light: only your own cell is half lit
        return 0.5 if d == 0 else 0.22
    return max(0.15, 1 - d / (rng + 1.5))


def pattern(b):
    return next(p for limit, p in PATTERNS if b >= limit)


def main():
    out = ['* Generated by tools/mktables.py. Do not edit.', '',
           'VIEWW   equ     %d' % VIEW_W, 'VIEWH   equ     %d' % VIEW_H, 'VIEWBYTES equ   %d' % (VIEW_H * 160),
           'NDEPTH3 equ     %d' % DEPTHS, '']
    vl = [round(CX - HW * k(z)) for z in range(DEPTHS)]
    vr = [min(VIEW_W - 1, round(CX + HW * k(z))) for z in range(DEPTHS)]
    vt = [round(CY - HH * k(z)) for z in range(DEPTHS)]
    vb = [min(VIEW_H - 1, round(CY + HH * k(z))) for z in range(DEPTHS)]
    # side-passage cutoff: the reference's "outer = CX + s * 3 * HW * f.k"
    vol = [round(CX - 3 * HW * k(z)) for z in range(DEPTHS)]
    vor = [round(CX + 3 * HW * k(z)) for z in range(DEPTHS)]
    w = lambda name, op, vals, note: out.append('%-7s %-7s %s  ; %s' % (name, op, ','.join(str(v) for v in vals), note))
    w('vl', 'fdb', vl, 'left edge x at depth z')
    w('vr', 'fdb', vr, 'right edge x')
    w('vt', 'fcb', vt, 'top y')
    w('vb', 'fcb', vb, 'bottom y')
    w('vol', 'fdb', vol, 'left side-passage cutoff (signed)')
    w('vor', 'fdb', vor, 'right side-passage cutoff')
    out += ['', '* Shade level for each light row (0 = no light, 1-8 = range) and depth in thirds',
            'VPATW   equ     %d' % DEPTHS, 'vpat']
    for rng in range(9):
        out.append('        fcb     ' + ','.join('%d' % pattern(bright(i / 3, rng)) for i in range(DEPTHS))
                   + '  ; ' + ('no light' if rng == 0 else 'range %d' % rng))
    # Ladders (the reference's renderMain): a trapezoid from 0.2 to 0.8 into the cell, half-width
    # 0.35 * HW * k; rails and rungs at 0.7 of that; rungs at 0.35, 0.5, 0.65. One row per cell
    # near-edge depth in thirds, from -2 (gliding past the cell you're in) to DEPTHS-1; each row has
    # 5 positions (0.2, 0.35, 0.5, 0.65, 0.8) of: floor y, ceiling y, half-width, rail half-width.
    out += ['', '* Ladder geometry: row = near-edge depth in thirds + 2; 5 x (floor y, ceiling y, half-width, rail)',
            'LTABROW equ     20', 'ltab']
    for base in range(-2, DEPTHS):
        vals = []
        for off in (0.2, 0.35, 0.5, 0.65, 0.8):
            z = max(0.0, base / 3 + off)
            kk = 1 / (1 + 0.85 * z)
            hw = HW * kk * 0.35
            vals += [min(VIEW_H - 1, round(CY + HH * kk)), round(CY - HH * kk), round(hw), round(hw * 0.7)]
        out.append('        fcb     ' + ','.join(str(v) for v in vals) + '  ; %d' % base)
    # Overhead map geometry per level (S = 21 + 2n). The maze fills text rows 1-21 (y 8-175); a cell
    # is ch rows tall and cw = 2.5 ch pixels wide, which looks square on a monitor (pixels are about
    # 2.5 times taller than wide). Then the ladder V's and the player arrow's sizes, as the reference
    # (0.3/0.2 of a cell for the V, 0.38 for the arrow, 0.7 of that for its back corners; across a
    # vertical arrow 0.9, since pixels are narrow: Steve found it too thin).
    # Items on the floor (the reference's renderMain): at depth d + 0.45, drawn if that's more than
    # 0.15 in front of the eye; scale s = HH * k * 0.55 in the reference's units, and side by side
    # 0.55 * HH * k apart when several share a cell. Converted to CoCo pixels (x 0.8, y 136/440).
    # Per row (cell near edge in thirds, -2 up): drawn?, floor y, x scale, y scale (both per 1/100
    # unit, times 256), half the spacing in pixels.
    out += ['', '* Items: row = near-edge depth in thirds + 2; drawn?, floor y, x scale, y scale, half spacing',
            'ITABROW equ     5', 'itab']
    for base in range(-2, DEPTHS):
        # Steve: items in your own cell sat too far off (0.45 reads as the next cell). The nearest
        # depth is 0.2 instead, blending back to the reference's d + 0.45 one cell out (base 3).
        iz = base / 3 + 0.45 if base >= 3 else 0.2 + base * (1.45 - 0.2) / 3
        kk = 1 / (1 + 0.85 * max(0.0, iz))
        s_ref = 220 * kk * 0.55
        vals = [1 if iz > 0.15 else 0, min(VIEW_H - 1, round(CY + HH * kk)),
                min(255, round(s_ref * 0.8 / 100 * 256)), min(255, round(s_ref * 136 / 440 / 100 * 256)),
                round(0.55 * 220 * kk * 0.8 / 2)]
        out.append('        fcb     ' + ','.join(str(v) for v in vals) + '  ; %d' % base)
    # Monsters (the reference's renderMain): straight ahead at depth max(0.3, d - 0.15), scale
    # HH * k * 1.2; one in a side passage beside cell d peeks round the doorway at max(0.35, d + 0.5),
    # shifted 0.58 of its scale toward the passage. Scales per 1/60 unit, times 64 (shapes are in 1/60).
    # Per row (cell near edge in thirds, -2 up): ahead: floor y, x scale, y scale; side: floor y, x scale,
    # y scale, shift in pixels.
    out += ['', '* Monsters: row = near-edge depth in thirds + 2; ahead floor y, x scale, y scale;',
            '* side floor y, x scale, y scale, shift', 'MTABROW equ     7', 'mtab']
    def mon_at(z):
        kk = 1 / (1 + 0.85 * z)
        s_ref = 220 * kk * 1.2
        return kk, s_ref, [min(VIEW_H - 1, round(CY + HH * kk)), min(255, round(s_ref * 0.8 / 60 * 64)),
                           min(255, round(s_ref * 136 / 440 / 60 * 64))]
    for base in range(-2, DEPTHS):
        _, _, ahead = mon_at(max(0.3, base / 3 - 0.15))
        _, s_ref, side = mon_at(max(0.35, base / 3 + 0.5))
        out.append('        fcb     ' + ','.join(str(v) for v in ahead + side + [round(s_ref * 0.58 * 0.8)])
                   + '  ; %d' % base)
    out += ['', '* Map geometry, level 1-5: S, ch, cw, ox (2), oy, V half-width, V top, V bottom,',
            '* arrow x, arrow y, arrow back x, arrow back y, item diamond x, y', 'MAPTABW equ     15', 'maptab']
    for n in range(1, 6):
        S = 21 + 2 * n
        ch = 168 // S
        cw = ch * 5 // 2
        ox = (640 - S * cw) // 2
        oy = 8 + (168 - S * ch) // 2
        rx, ry = round(0.38 * cw), round(0.38 * ch)
        vals = [S, ch, cw, ox >> 8, ox & 255, oy, round(0.3 * cw), round(0.2 * ch), round(0.3 * ch),
                rx, ry, int(0.9 * rx + 0.5), round(0.7 * ry), round(0.28 * cw), round(0.28 * ch)]
        out.append('        fcb     ' + ','.join(str(v) for v in vals) + '  ; level %d' % n)
    out += ['', '* Screen row start addresses (screen mapped at SCRCPU), rows 0-191', 'rowaddr']
    for y in range(0, 192, 8):
        out.append('        fdb     ' + ','.join('SCRCPU+%d' % ((y + i) * 160) for i in range(8)))
    # 320x16 screen: 2 pixels per byte, x here is the screen's 0-319 (line halves the callers' x)
    out += ['', 'pixmask fcb     $F0,$0F         ; the pixel at x & 1',
            'lmaskl  fcb     $FF,$0F         ; pixels x & 1 .. 1 (left end of a horizontal line)',
            'lmaskr  fcb     $F0,$FF         ; pixels 0 .. x & 1 (right end)']
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
